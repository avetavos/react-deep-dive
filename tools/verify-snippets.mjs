#!/usr/bin/env node
// Snippet-verification harness for the bilingual React Deep Dive course.
//
// This course has no in-browser playground (unlike the Go/Python/Node Learn
// Hub courses), so the only way to prove a lesson's code snippets actually
// compile — and, for behavior claims ("re-renders twice", "cleanup runs
// before the next effect"), actually run — is a real Vite React+TS project
// ("the probe", tools/probe/, gitignored) plus `tsc --noEmit` (fast, every
// fence) and `vitest run` (for fences that are tests).
//
// Usage:
//   node tools/verify-snippets.mjs                 type-check every collected
//                                                   fence from src/content/docs/en
//   node tools/verify-snippets.mjs --refresh        wipe + rescaffold tools/probe first
//   node tools/verify-snippets.mjs --test [module/lesson]
//                                                   run vitest over collected *.test.ts(x)
//                                                   fences (all, or one lesson's namespace)
//   node tools/verify-snippets.mjs --self-test      harness self-check (see selfTest())
//
// Fence convention (spec §5.0): a fence in `tsx|ts` whose FIRST line is a
// path comment (`// src/components/Counter.tsx`, `// src/__tests__/counter.test.tsx`)
// is a real file and gets collected. A first line containing `@expect-error`
// is a deliberate-error demo and is skipped (the lesson prose carries the
// real error text). Anything else is a fragment with no path comment and is
// skipped (expected today — Phase 3 hasn't retrofitted path comments yet).
// A fence whose path ends `.test.ts`/`.test.tsx` is additionally counted as
// a "test" fence and picked up by `--test` via vitest's own include glob.
//
// Namespacing / cross-lesson imports: every collected fence is written to
// `tools/probe/lessons/<module>__<lesson>/<path>` (namespaced per lesson, so
// two lessons can each define `src/components/Counter.tsx` without
// colliding). This course uses plain relative imports (no `@/` alias), so a
// fence importing `./Counter` or `../hooks/useCounter` resolves naturally
// inside its own namespace directory — the same layout the lesson's path
// comments describe. When a fence imports a relative path that does NOT
// exist as a collected fence in its own lesson, but another lesson defines
// that exact path (via its own bare path-comment fence), the specifier is
// rewritten at write time to point at that lesson's copy instead — the
// first lesson (in module/file order) that defines it wins, mirroring
// nextjs-deep-dive's `@/` cross-lesson rule. This lets a later lesson reuse
// a component/hook a prior lesson already defined, the way a real project
// would, without every lesson re-authoring the same file.

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, mkdtempSync, globSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';

const REPO_ROOT = path.resolve(import.meta.dirname, '..');
const PROBE_DIR = path.join(REPO_ROOT, 'tools/probe');
const LESSONS_DIR = path.join(PROBE_DIR, 'lessons');
const DOCS_EN = path.join(REPO_ROOT, 'src/content/docs/en');

const FENCE_LANGS = new Set(['tsx', 'ts']);
const PATH_RE = /^\/\/ ([\w@.\-[\]()/]+\.(tsx|ts))$/;

// Dev dependencies `npm create vite -- --template react-ts` does NOT ship,
// needed for the vitest + React Testing Library probe. Skipped when already
// present (true on a freshly `cp -R`'d scaffold — see README's Harness section).
const EXTRA_DEV_PACKAGES = ['vitest', 'jsdom', '@testing-library/react', '@testing-library/jest-dom', '@testing-library/user-event'];

const VITEST_CONFIG_SRC = `import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';

// Generated by tools/verify-snippets.mjs — safe to regenerate, do not hand-edit.
export default defineConfig({
  plugins: [react()],
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./vitest.setup.ts'],
    include: ['lessons/**/*.test.{ts,tsx}'],
  },
});
`;

const VITEST_SETUP_SRC = `import '@testing-library/jest-dom/vitest';\n`;

// ---------------------------------------------------------------------------
// String/bracket scanning helpers, ported from tools/check-parity.mjs (same
// technique that file uses to keep quiz-array template literals and
// `<SpotTheBug code={\`...\`}>` props from confusing a naive fence regex:
// walk the source honoring string literals so brackets/backticks *inside* a
// string never look like real structure).
// ---------------------------------------------------------------------------

function parseStringAt(text, i) {
  const quote = text[i];
  let j = i + 1;
  while (j < text.length) {
    const c = text[j];
    if (c === '\\') {
      j += 2;
      continue;
    }
    if (c === quote) {
      j++;
      break;
    }
    j++;
  }
  return { end: j };
}

function scanBalanced(text, start, open, close) {
  let depth = 1;
  let i = start;
  while (i < text.length && depth > 0) {
    const c = text[i];
    if (c === '"' || c === "'" || c === '`') {
      i = parseStringAt(text, i).end;
      continue;
    }
    if (c === open) depth++;
    else if (c === close) depth--;
    i++;
  }
  return i; // index right after the matching close
}

// Ranges of `export const xxx = [ ... ]` (quiz question arrays) and
// `<SpotTheBug code={\` ... \`}>` template literals — this course has no
// hoisted `export const xxxCode` playground literals (spec §1), so those two
// are the only places a fence-looking ``` sequence can hide inside a string.
function findExcludedRanges(src) {
  const ranges = [];
  {
    const re = /export\s+const\s+\w+\s*=\s*\[/g;
    let m;
    while ((m = re.exec(src))) {
      const end = scanBalanced(src, re.lastIndex, '[', ']');
      ranges.push([m.index, end]);
      re.lastIndex = end;
    }
  }
  {
    const re = /<SpotTheBug\s+code=\{\s*`/g;
    let m;
    while ((m = re.exec(src))) {
      const backtickIdx = m.index + m[0].length - 1;
      const { end } = parseStringAt(src, backtickIdx);
      ranges.push([m.index, end]);
      re.lastIndex = end;
    }
  }
  return ranges;
}

// Blank out excluded ranges but keep every newline they contain, so line
// numbers computed on the result still match the original file.
function stripExcluded(src, ranges) {
  if (!ranges.length) return src;
  ranges.sort((a, b) => a[0] - b[0]);
  let out = '';
  let cursor = 0;
  for (const [start, end] of ranges) {
    if (start < cursor) continue; // overlapping/malformed match, ignore
    out += src.slice(cursor, start);
    out += src.slice(start, end).replace(/[^\n]/g, '');
    cursor = end;
  }
  out += src.slice(cursor);
  return out;
}

function countNewlinesBefore(s, upto) {
  let n = 0;
  for (let i = 0; i < upto; i++) if (s.charCodeAt(i) === 10) n++;
  return n;
}

// Collect every fenced code block in one MDX file's source.
// Returns [{ fenceNum, lang, line, category, path?, body? }], fenceNum is
// 1-based over ALL real fences (any language) in document order.
function collectFences(rawSrc) {
  const src = stripExcluded(rawSrc, findExcludedRanges(rawSrc));
  const fenceRe = /```([\w-]*)[^\n]*\n([\s\S]*?)```/g;
  const results = [];
  let fenceNum = 0;
  let m;
  while ((m = fenceRe.exec(src))) {
    fenceNum++;
    const lang = m[1];
    if (!FENCE_LANGS.has(lang)) continue; // out of scope for this harness
    const body = m[2];
    const line = countNewlinesBefore(src, m.index) + 1;
    const firstLine = body.split('\n', 1)[0].trim();
    if (firstLine.includes('@expect-error')) {
      results.push({ fenceNum, lang, line, category: 'expect-error' });
      continue;
    }
    const pm = PATH_RE.exec(firstLine);
    if (pm) {
      results.push({ fenceNum, lang, line, category: 'collected', path: pm[1], body });
    } else {
      results.push({ fenceNum, lang, line, category: 'skipped-no-path' });
    }
  }
  return results;
}

// Rewrite relative (`./`, `../`) specifiers in a fence body that resolve
// outside its own lesson namespace to the first other lesson (in module
// order) that defines that exact path — see file-header note. Bare
// specifiers (npm packages, `react`, etc.) are left untouched.
function rewriteRelativeSpecifiers(content, relPath, namespace, owners, ownKeys) {
  const dir = path.posix.dirname(relPath.replaceAll('\\', '/'));
  const here = path.posix.join(namespace, dir);
  return content.replace(
    /\b(from|import|require)(\s*\(?\s*)(['"])(\.\.?\/[^'"]*)\3/g,
    (whole, kw, ws, q, spec) => {
      const resolvedFull = path.posix.normalize(path.posix.join(dir, spec));
      const key = resolvedFull.replace(/\.tsx?$/, '');
      if (ownKeys.has(key)) return whole; // this lesson defines it itself — resolves naturally
      const candidates = owners.get(key);
      if (!candidates || !candidates.length) return whole; // unknown file — a real missing-module tsc error is correct here
      const ownerNs = candidates[0];
      let rel = path.posix.relative(here, path.posix.join(ownerNs, resolvedFull));
      if (!rel.startsWith('.')) rel = `./${rel}`;
      return `${kw}${ws}${q}${rel}${q}`;
    },
  );
}

// ---------------------------------------------------------------------------
// Probe lifecycle
// ---------------------------------------------------------------------------

function ensureProbe(refresh) {
  if (refresh && existsSync(PROBE_DIR)) rmSync(PROBE_DIR, { recursive: true, force: true });
  if (!existsSync(PROBE_DIR)) {
    console.log('tools/probe missing — scaffolding with create-vite (react-ts template)...');
    const create = spawnSync('npx', ['-y', 'create-vite@latest', 'probe', '--template', 'react-ts'], {
      cwd: path.join(REPO_ROOT, 'tools'),
      stdio: 'inherit',
    });
    if (create.status !== 0) {
      console.error('probe scaffold failed');
      process.exit(1);
    }
    rmSync(path.join(PROBE_DIR, '.git'), { recursive: true, force: true });
    const install = spawnSync('npm', ['install'], { cwd: PROBE_DIR, stdio: 'inherit' });
    if (install.status !== 0) {
      console.error('probe npm install failed');
      process.exit(1);
    }
  }
  installExtraPackages();
  patchTsconfig();
  writeFileSync(path.join(PROBE_DIR, 'vitest.config.ts'), VITEST_CONFIG_SRC);
  writeFileSync(path.join(PROBE_DIR, 'vitest.setup.ts'), VITEST_SETUP_SRC);
}

function installExtraPackages() {
  const missing = EXTRA_DEV_PACKAGES.filter((pkg) => !existsSync(path.join(PROBE_DIR, 'node_modules', pkg)));
  if (!missing.length) return;
  console.log(`installing missing probe dev dependencies: ${missing.join(', ')}`);
  const res = spawnSync('npm', ['install', '--save-dev', '--no-audit', '--no-fund', ...missing], {
    cwd: PROBE_DIR,
    stdio: 'inherit',
  });
  if (res.status !== 0) {
    console.error('installing probe dev dependencies failed');
    process.exit(1);
  }
}

// Text-patch tools/probe/tsconfig.app.json (comments in that file mean it's
// not valid JSON.parse input — Vite's own template ships JSONC — so this
// does targeted, idempotent string replacements instead of parse/stringify,
// which would also silently drop the file's own comments).
function patchTsconfig() {
  const p = path.join(PROBE_DIR, 'tsconfig.app.json');
  let src = readFileSync(p, 'utf8');
  const before = src;
  if (!src.includes('"lessons/**/*"')) {
    src = src.replace('"include": ["src"]', '"include": ["src", "lessons/**/*", "vitest.setup.ts"]');
  }
  if (!/"strict"\s*:\s*true/.test(src)) {
    src = src.replace('"jsx": "react-jsx",', '"jsx": "react-jsx",\n    "strict": true,');
  }
  if (!src.includes('vitest/globals')) {
    src = src.replace('"types": ["vite/client"],', '"types": ["vite/client", "vitest/globals", "@testing-library/jest-dom"],');
  }
  if (src !== before) writeFileSync(p, src);
}

// ---------------------------------------------------------------------------
// Lesson discovery
// ---------------------------------------------------------------------------

function discoverLessons() {
  const rels = globSync('**/*.mdx', { cwd: DOCS_EN }).sort();
  return rels.map((rel) => {
    const posixRel = rel.replaceAll('\\', '/');
    return {
      absPath: path.join(DOCS_EN, rel),
      mdxRelPath: `src/content/docs/en/${posixRel}`,
      module: posixRel.split('/')[0],
      lesson: path.basename(posixRel, '.mdx'),
    };
  });
}

// ---------------------------------------------------------------------------
// Shared: collect fences from descriptors + write the lessons/ tree
// ---------------------------------------------------------------------------

function buildLessonsTree(descriptors) {
  rmSync(LESSONS_DIR, { recursive: true, force: true });
  mkdirSync(LESSONS_DIR, { recursive: true });

  const fenceMap = new Map(); // namespace -> { mdxRelPath, module, lesson, fences: Map(relPath -> fenceNum) }
  const stats = new Map(); // module -> { collected, skippedNoPath, expectError, tests }
  const owners = new Map(); // path-without-ext -> [namespace, ...] in module/file order
  const nsKeys = new Map(); // namespace -> Set(path-without-ext) it defines itself
  const pending = []; // [namespace, fence]

  for (const d of descriptors) {
    const counters = stats.get(d.module) ?? { collected: 0, skippedNoPath: 0, expectError: 0, tests: 0 };
    stats.set(d.module, counters);

    const namespace = `${d.module}__${d.lesson}`;
    const nsFences = new Map();
    const keys = new Set();
    const src = readFileSync(d.absPath, 'utf8');

    for (const f of collectFences(src)) {
      if (f.category === 'collected') {
        counters.collected++;
        if (/\.test\.tsx?$/.test(f.path)) counters.tests++;
        nsFences.set(f.path, f.fenceNum);
        const key = f.path.replace(/\.tsx?$/, '');
        keys.add(key);
        const list = owners.get(key) ?? [];
        if (!list.includes(namespace)) list.push(namespace);
        owners.set(key, list);
        pending.push([namespace, f]);
      } else if (f.category === 'skipped-no-path') {
        counters.skippedNoPath++;
      } else if (f.category === 'expect-error') {
        counters.expectError++;
      }
    }
    fenceMap.set(namespace, { mdxRelPath: d.mdxRelPath, module: d.module, lesson: d.lesson, fences: nsFences });
    nsKeys.set(namespace, keys);
  }

  for (const [namespace, f] of pending) {
    const destAbs = path.join(LESSONS_DIR, namespace, f.path);
    mkdirSync(path.dirname(destAbs), { recursive: true });
    writeFileSync(destAbs, rewriteRelativeSpecifiers(f.body, f.path, namespace, owners, nsKeys.get(namespace)));
  }

  return { fenceMap, stats };
}

function printStats(stats) {
  console.log('\nPer-module fence summary (collected / skipped-no-path / expect-error / tests):');
  const totals = { collected: 0, skippedNoPath: 0, expectError: 0, tests: 0 };
  for (const [module, c] of [...stats.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    console.log(`  ${module}: ${c.collected} / ${c.skippedNoPath} / ${c.expectError} / ${c.tests}`);
    totals.collected += c.collected;
    totals.skippedNoPath += c.skippedNoPath;
    totals.expectError += c.expectError;
    totals.tests += c.tests;
  }
  console.log(`  TOTAL: ${totals.collected} / ${totals.skippedNoPath} / ${totals.expectError} / ${totals.tests}`);
}

// ---------------------------------------------------------------------------
// Type-check mode (default): tsc --noEmit over tools/probe/tsconfig.app.json
// ---------------------------------------------------------------------------

function runTypeCheck(descriptors) {
  const { fenceMap, stats } = buildLessonsTree(descriptors);

  // The probe's root tsconfig.json is Vite's solution-style file (`files: []`
  // + `references`), which only does real work under `tsc -b`. Pointing
  // straight at tsconfig.app.json (the one with `include`/`jsx`/`strict`/
  // `types`, patched above) is the minimal-diff way to get a plain
  // `--noEmit` check without adopting composite/build-mode project refs.
  const tscBin = path.join(PROBE_DIR, 'node_modules', '.bin', 'tsc');
  const res = spawnSync(tscBin, ['--noEmit', '--pretty', 'false', '-p', 'tsconfig.app.json'], {
    cwd: PROBE_DIR,
    encoding: 'utf8',
  });
  if (res.error) {
    console.error('failed to run tsc in the probe:', res.error.message);
    process.exit(1);
  }

  const diagLine = /^(.+?)\((\d+),(\d+)\): error (TS\d+): (.+)$/gm;
  const diagnostics = [];
  let dm;
  const stdout = res.stdout ?? '';
  while ((dm = diagLine.exec(stdout))) {
    const [, file, line, col, code, message] = dm;
    const norm = file.replaceAll('\\', '/');
    const lm = /^lessons\/([^/]+)\/(.+)$/.exec(norm);
    const info = lm && fenceMap.get(lm[1]);
    const mapped = info ? { mdxRelPath: info.mdxRelPath, relPath: lm[2], fenceNum: info.fences.get(lm[2]) } : null;
    diagnostics.push({ file: norm, line, col, code, message, mapped });
  }

  if (diagnostics.length) {
    console.log(`\n${diagnostics.length} type error(s):\n`);
    for (const d of diagnostics) {
      if (d.mapped) {
        console.log(
          `${d.mapped.mdxRelPath}:fence #${d.mapped.fenceNum} (${d.mapped.relPath}) ` +
            `— probe:${d.file}:${d.line}:${d.col} ${d.code}: ${d.message}`,
        );
      } else {
        console.log(`[unmapped] ${d.file}:${d.line}:${d.col} ${d.code}: ${d.message}`);
      }
    }
  } else if (res.status !== 0) {
    console.log('\ntsc exited non-zero but no parseable diagnostics were found; raw output:\n');
    console.log(stdout, res.stderr ?? '');
  } else {
    console.log('\nno type errors.');
  }

  printStats(stats);

  return { errorCount: diagnostics.length || (res.status !== 0 ? 1 : 0), diagnostics, stats };
}

// ---------------------------------------------------------------------------
// --test [module/lesson]: vitest over collected *.test.ts(x) fences
// ---------------------------------------------------------------------------

function buildAndRunVitest(descriptors, target) {
  const { fenceMap } = buildLessonsTree(descriptors);

  let filterArg = null;
  if (target) {
    const parts = target.split('/');
    const lesson = parts.pop();
    const module = parts.join('/');
    const namespace = `${module}__${lesson}`;
    if (!fenceMap.has(namespace)) {
      console.error(`no such lesson: ${target}`);
      process.exit(1);
    }
    filterArg = `lessons/${namespace}`;
  }

  const outFile = path.join(os.tmpdir(), `verify-snippets-vitest-${process.pid}-${Date.now()}.json`);
  const vitestBin = path.join(PROBE_DIR, 'node_modules', '.bin', 'vitest');
  const args = ['run', '--passWithNoTests', '--reporter=json', `--outputFile=${outFile}`];
  if (filterArg) args.push(filterArg);
  const res = spawnSync(vitestBin, args, { cwd: PROBE_DIR, encoding: 'utf8' });

  let report = null;
  if (existsSync(outFile)) {
    try {
      report = JSON.parse(readFileSync(outFile, 'utf8'));
    } catch {
      // leave report null; caller falls back to raw output
    }
    rmSync(outFile, { force: true });
  }

  return { fenceMap, report, status: res.status, stdout: res.stdout, stderr: res.stderr };
}

function testMode(target) {
  const { fenceMap, report, status, stdout, stderr } = buildAndRunVitest(discoverLessons(), target);

  if (!report) {
    console.log((stdout ?? '') + (stderr ?? ''));
    process.exit(status ?? 1);
  }

  const byLesson = new Map(); // "module/lesson" -> testResults[]
  for (const tr of report.testResults ?? []) {
    const m = /lessons\/([^/]+)\//.exec((tr.name ?? '').replaceAll('\\', '/'));
    const info = m && fenceMap.get(m[1]);
    const label = info ? `${info.module}/${info.lesson}` : (m ? m[1] : '[unmapped]');
    const list = byLesson.get(label) ?? [];
    list.push(tr);
    byLesson.set(label, list);
  }

  for (const [label, results] of [...byLesson.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const assertions = results.flatMap((r) => r.assertionResults ?? []);
    const passed = assertions.filter((a) => a.status === 'passed').length;
    console.log(`${label}: ${passed}/${assertions.length} passed`);
    for (const a of assertions.filter((a) => a.status === 'failed')) {
      const firstLine = (a.failureMessages?.[0] ?? '').split('\n')[0];
      console.log(`  FAIL ${(a.fullName ?? a.title).trim()}: ${firstLine}`);
    }
  }

  console.log(`\n${report.numPassedTests ?? 0}/${report.numTotalTests ?? 0} test(s) passed across ${report.testResults?.length ?? 0} file(s).`);
  process.exit(status ?? (report.success ? 0 : 1));
}

// ---------------------------------------------------------------------------
// --self-test
// ---------------------------------------------------------------------------

function selfTest() {
  const tmpDir = mkdtempSync(path.join(os.tmpdir(), 'verify-snippets-selftest-'));
  const badPath = path.join(tmpDir, 'bad.mdx');
  const goodPath = path.join(tmpDir, 'good.mdx');

  writeFileSync(
    badPath,
    [
      '---',
      'title: selftest',
      '---',
      '',
      '```ts',
      '// src/selftest/bad.ts',
      'const x: number = "not a number";',
      'export default x;',
      '```',
      '',
      '```ts',
      '// src/selftest/bad.test.ts',
      "it('fails on purpose', () => { expect(1).toBe(2); });",
      '```',
      '',
    ].join('\n'),
  );
  writeFileSync(goodPath, ['```ts', '// src/selftest/good.ts', 'export const y: number = 1;', '```', ''].join('\n'));

  const descriptors = [
    { absPath: badPath, mdxRelPath: 'selftest/bad.mdx', module: 'selftest', lesson: 'bad' },
    { absPath: goodPath, mdxRelPath: 'selftest/good.mdx', module: 'selftest', lesson: 'good' },
  ];

  const { diagnostics } = runTypeCheck(descriptors);
  const badTypeFailed = diagnostics.some((d) => d.mapped?.relPath === 'src/selftest/bad.ts');
  const goodTypePassed = !diagnostics.some((d) => d.mapped?.mdxRelPath === 'selftest/good.mdx');
  // The failing-assertion test fence is valid TypeScript — it must NOT show up as a tsc error.
  const testFenceTypeClean = !diagnostics.some((d) => d.mapped?.relPath === 'src/selftest/bad.test.ts');

  const { report } = buildAndRunVitest(descriptors, 'selftest/bad');
  const testAssertions = (report?.testResults ?? []).flatMap((r) => r.assertionResults ?? []);
  const testFenceFailedUnderVitest = testAssertions.some((a) => a.status === 'failed');

  rmSync(tmpDir, { recursive: true, force: true });
  rmSync(LESSONS_DIR, { recursive: true, force: true });

  const ok = badTypeFailed && goodTypePassed && testFenceTypeClean && testFenceFailedUnderVitest;
  if (ok) {
    console.log('\nself-test: PASS (bad-type fence failed tsc, good fence passed tsc, failing test fence failed vitest)');
    process.exit(0);
  }
  console.error('\nself-test: FAIL', { badTypeFailed, goodTypePassed, testFenceTypeClean, testFenceFailedUnderVitest });
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

function main() {
  const args = process.argv.slice(2);
  ensureProbe(args.includes('--refresh'));

  if (args.includes('--self-test')) return selfTest();

  const testIdx = args.indexOf('--test');
  if (testIdx !== -1) return testMode(args[testIdx + 1]);

  const { errorCount } = runTypeCheck(discoverLessons());
  process.exit(errorCount > 0 ? 1 : 0);
}

main();
